export function getKpiGlossary(kpiId, subLabel) {
  if (subLabel) return MANAGEMENT_GLOSSARY[`${kpiId}::${subLabel}`] || null;
  return MANAGEMENT_GLOSSARY[kpiId] || null;
}

/** Lookup KPI meta by id. */
export function getKpiMeta(id) {
  return MANAGEMENT_KPI_CATALOG.find((k) => k.id === id) || null;
}

/** KPI ids grouped by row. */
export function kpisByRow(rowId) {
  return MANAGEMENT_KPI_CATALOG.filter((k) => k.rowId === rowId);
}
